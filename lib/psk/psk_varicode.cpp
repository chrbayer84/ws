static uint32_t varicodetab2[256];

static void build_varicodetab2() {
    for (int c = 0; c < 256; c++) {
        const char* encoded = varicodetab1[c];
        uint32_t symbol = 0;
        for (int i = 0; encoded[i]; i++) {
            symbol = (symbol << 1) | (encoded[i] - '0');
        }
        varicodetab2[c] = symbol;
    }
}

struct VaricodeTableInitializer {
    VaricodeTableInitializer() { build_varicodetab2(); }
} varicode_table_initializer;

const char* varicode_encode(uint8_t c) {
    return varicodetab1[c];
}

int varicode_decode(uint32_t symbol) {
    for (int i = 0; i < 256; i++) {
        if (symbol == varicodetab2[i]) {
            return i;
        }
    }
    return -1;
}

